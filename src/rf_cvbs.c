/* CVBS file sink, as used by decode-orc, ld-decode and vhs-decode.
 *
 * The baseband signal generated by hacktv is resampled to 4 x fsc of the
 * matching video standard preset (PAL, NTSC, PAL_M or SECAM) and stored as
 * 10-bit sample values (CVBS_U10_4FSC or CVBS_U16_4FSC). Frames start with
 * the first sample at or after 0H of line 1, as required by the
 * specification. A SQLite .meta file describing the presets is written
 * alongside the sample data when hacktv is built with SQLite support.
 *
 * Composite modes write <basename>.cvbs, S-Video (--s-video) writes
 * <basename>.cvbsy and <basename>.cvbsc.
*/

#include <stdio.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
#include <unistd.h>
#include <sys/types.h>
#ifdef HAVE_SQLITE3
#include <sqlite3.h>
#endif
#include "rf.h"
#include "video.h"

/* Number of fractional positions in the resampler's polyphase table */
#define _PHASES 1024

/* Output samples buffered before writing */
#define _OUT_LEN 4096

typedef struct {

	const char *name;
	int sync;
	int blanking;
	int black;
	int white;

	/* Samples per frame at 4 x fsc */
	int64_t frame_samples;

} _cvbs_preset_t;

static const _cvbs_preset_t _preset_pal   = { "PAL",   4, 256, 256, 844, 709379 };
static const _cvbs_preset_t _preset_ntsc  = { "NTSC",  16, 240, 282, 800, 477750 };
static const _cvbs_preset_t _preset_pal_m = { "PAL_M", 16, 240, 282, 800, 477225 };
static const _cvbs_preset_t _preset_secam = { "SECAM", 4, 256, 256, 844, 709379 };

typedef struct {
	FILE *f;
	char *filename;

	/* Input history, in hacktv's int16 sample domain */
	float *in;
	int in_len;
	int in_size;

	/* Value used to pad the start and end of the signal */
	float pad;

	/* 10-bit mapping */
	double offset16;
	double offset10;

	/* Output buffer */
	uint8_t *out;
	int out_len;

} _cvbs_channel_t;

typedef struct {

	const _cvbs_preset_t *preset;
	const char *signal_state;
	int encoding;
	int yc;
	int nch;
	_cvbs_channel_t ch[2];

	char *basename;
	char *notes;
	int black_level;

	/* 10-bit units per hacktv int16 unit */
	double scale;

	/* Polyphase resampler */
	float *taps;
	int ntaps;

	/* Input sample index of in[0] */
	int64_t in_base;

	/* Position of the next output sample in input samples: ip + fr / q */
	int64_t ip;
	int64_t fr;
	int64_t q;
	int64_t step_i;
	int64_t step_f;

	/* Sample counters */
	int64_t in_samples;
	int64_t out_samples;
	r64_t in_rate;
	r64_t frame_rate;

	/* Number of clipped output samples */
	int64_t clipped;

} rf_cvbs_t;

static double _sinc(double x)
{
	return(x == 0 ? 1.0 : sin(M_PI * x) / (M_PI * x));
}

static int _init_taps(rf_cvbs_t *rf, double cutoff)
{
	int p, k, half;

	/* cutoff is the -6dB point in cycles per input sample. The filter
	 * spans 12 zero crossings either side of the centre. */
	half = ceil(12.0 / (2.0 * cutoff));
	rf->ntaps = half * 2;

	rf->taps = malloc(sizeof(float) * rf->ntaps * (_PHASES + 1));
	if(!rf->taps)
	{
		return(RF_OUT_OF_MEMORY);
	}

	for(p = 0; p <= _PHASES; p++)
	{
		float *t = &rf->taps[p * rf->ntaps];
		double sum = 0;

		for(k = 0; k < rf->ntaps; k++)
		{
			/* Distance from the output position, in input samples */
			double x = (k - half + 1) - (double) p / _PHASES;
			double w = x / half;

			/* Blackman window */
			w = fabs(w) >= 1.0 ? 0.0 : 0.42 + 0.5 * cos(M_PI * w) + 0.08 * cos(2.0 * M_PI * w);

			t[k] = 2.0 * cutoff * _sinc(2.0 * cutoff * x) * w;
			sum += t[k];
		}

		/* Normalise for unity gain at DC, so the signal levels are exact */
		for(k = 0; k < rf->ntaps; k++)
		{
			t[k] /= sum;
		}
	}

	return(RF_OK);
}

static int _flush_channel(_cvbs_channel_t *ch)
{
	if(ch->out_len > 0)
	{
		if(fwrite(ch->out, 2, ch->out_len, ch->f) != ch->out_len)
		{
			perror(ch->filename);
			return(RF_ERROR);
		}

		ch->out_len = 0;
	}

	return(RF_OK);
}

/* Generate all output samples for which enough input is available */
static int _resample(rf_cvbs_t *rf)
{
	int c, k;

	while(rf->ip + rf->ntaps / 2 < rf->in_base + rf->ch[0].in_len)
	{
		int p = ((rf->fr * _PHASES) + rf->q / 2) / rf->q;
		const float *t = &rf->taps[p * rf->ntaps];
		int64_t x = rf->ip - rf->ntaps / 2 + 1 - rf->in_base;

		for(c = 0; c < rf->nch; c++)
		{
			_cvbs_channel_t *ch = &rf->ch[c];
			const float *in = &ch->in[x];
			double v = 0;
			int s;

			for(k = 0; k < rf->ntaps; k++)
			{
				v += t[k] * in[k];
			}

			/* Map to the 10-bit domain */
			s = lround(ch->offset10 + (v - ch->offset16) * rf->scale);

			/* Values 0-3 and 1020-1023 are reserved. Filter ringing of
			 * up to one step past the limits is not reported */
			if(s < 4 || s > 1019)
			{
				if(s < 3 || s > 1020) rf->clipped++;
				s = s < 4 ? 4 : 1019;
			}

			if(rf->encoding == RF_CVBS_U16) s <<= 6;

			/* Little-endian 16-bit words */
			ch->out[ch->out_len * 2 + 0] = s & 0xFF;
			ch->out[ch->out_len * 2 + 1] = (s >> 8) & 0xFF;

			if(++ch->out_len == _OUT_LEN)
			{
				if(_flush_channel(ch) != RF_OK) return(RF_ERROR);
			}
		}

		rf->out_samples++;

		/* Advance to the next output position */
		rf->ip += rf->step_i;
		rf->fr += rf->step_f;
		if(rf->fr >= rf->q)
		{
			rf->fr -= rf->q;
			rf->ip++;
		}
	}

	/* Drop input history that is no longer needed */
	k = rf->ip - rf->ntaps / 2 + 1 - rf->in_base;
	if(k > rf->ch[0].in_size / 2)
	{
		for(c = 0; c < rf->nch; c++)
		{
			_cvbs_channel_t *ch = &rf->ch[c];
			memmove(ch->in, &ch->in[k], sizeof(float) * (ch->in_len - k));
			ch->in_len -= k;
		}

		rf->in_base += k;
	}

	return(RF_OK);
}

static int _append(rf_cvbs_t *rf, const int16_t *iq_data, size_t samples)
{
	int c, i;

	while(samples > 0)
	{
		int n = rf->ch[0].in_size - rf->ch[0].in_len;

		if(n > samples) n = samples;

		for(c = 0; c < rf->nch; c++)
		{
			_cvbs_channel_t *ch = &rf->ch[c];

			for(i = 0; i < n; i++)
			{
				/* NULL input pads the signal */
				ch->in[ch->in_len + i] = iq_data ? iq_data[i * 2 + c] : ch->pad;
			}

			ch->in_len += n;
		}

		if(iq_data) iq_data += n * 2;
		samples -= n;

		if(_resample(rf) != RF_OK) return(RF_ERROR);
	}

	return(RF_OK);
}

static int _rf_cvbs_write(void *private, const int16_t *iq_data, size_t samples)
{
	rf_cvbs_t *rf = private;

	rf->in_samples += samples;

	return(_append(rf, iq_data, samples));
}

