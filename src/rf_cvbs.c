static void _free(rf_cvbs_t *rf)
{
	int c;

	for(c = 0; c < 2; c++)
	{
		_cvbs_channel_t *ch = &rf->ch[c];

		if(ch->f) fclose(ch->f);
		free(ch->filename);
		free(ch->in);
		free(ch->out);
	}

	free(rf->taps);
	free(rf->basename);
	free(rf->notes);
	free(rf);
}

static int _rf_cvbs_close(void *private)
{
	rf_cvbs_t *rf = private;
	int64_t frames;
	int64_t target;
	int c, r = RF_OK;

	/* Only complete frames are kept. hacktv normally stops on a frame
	 * boundary, but may be interrupted part way through a frame */
	frames = rf->in_samples * rf->frame_rate.num / (rf->in_rate.num * rf->frame_rate.den / rf->in_rate.den);
	target = frames * rf->preset->frame_samples;

	/* Pad the end of the signal until the final frame is complete */
	while(rf->out_samples < target && r == RF_OK)
	{
		r = _append(rf, NULL, rf->ntaps);
	}

	for(c = 0; c < rf->nch && r == RF_OK; c++)
	{
		_cvbs_channel_t *ch = &rf->ch[c];

		r = _flush_channel(ch);

		/* Discard any partial frame */
		if(r == RF_OK && rf->out_samples > target)
		{
			fflush(ch->f);

			if(ftruncate(fileno(ch->f), target * 2) != 0)
			{
				perror(ch->filename);
				r = RF_ERROR;
			}
		}
	}

	fprintf(stderr, "CVBS: %lld frames written (%s, %s, %s)\n",
		(long long) frames,
		rf->preset->name,
		rf->encoding == RF_CVBS_U16 ? "CVBS_U16_4FSC" : "CVBS_U10_4FSC",
		rf->signal_state
	);

	if(rf->clipped > 0)
	{
		fprintf(stderr, "CVBS: Warning: %lld samples were clipped to the legal 10-bit range\n", (long long) rf->clipped);
	}

#ifdef HAVE_SQLITE3
	if(r == RF_OK)
	{
		r = _write_meta(rf, frames);
	}
#else
	fprintf(stderr, "CVBS: hacktv was built without SQLite, no .meta file was written\n");
#endif

	_free(rf);

	return(r);
}

static int _open_channel(rf_cvbs_t *rf, _cvbs_channel_t *ch, const char *ext, double offset16, double offset10)
{
	ch->filename = malloc(strlen(rf->basename) + strlen(ext) + 1);
	if(!ch->filename)
	{
		return(RF_OUT_OF_MEMORY);
	}

	sprintf(ch->filename, "%s%s", rf->basename, ext);

	ch->f = fopen(ch->filename, "wb");
	if(!ch->f)
	{
		perror(ch->filename);
		return(RF_ERROR);
	}

	ch->offset16 = offset16;
	ch->offset10 = offset10;
	ch->pad = offset16;

	/* Room for at least one line of input at any sensible sample rate */
	ch->in_size = rf->ntaps + 65536;
	ch->in = malloc(sizeof(float) * ch->in_size);
	ch->out = malloc(2 * _OUT_LEN);
	if(!ch->in || !ch->out)
	{
		return(RF_OUT_OF_MEMORY);
	}

	/* Pre-fill the history so the first output sample is centred */
	for(ch->in_len = 0; ch->in_len < rf->ntaps; ch->in_len++)
	{
		ch->in[ch->in_len] = ch->pad;
	}

	return(RF_OK);
}

int rf_cvbs_open(rf_t *s, const char *filename, const vid_t *vid, int encoding, const char *notes)
{
	rf_cvbs_t *rf;
	const vid_config_t *conf = &vid->conf;
	r64_t fsc4, phase, ratio;
	double cutoff;
	const char *ext;
	int r;

	if(filename == NULL || strcmp(filename, "-") == 0)
	{
		fprintf(stderr, "CVBS output requires a filename.\n");
		return(RF_ERROR);
	}

	if(conf->modulation != VID_NONE || conf->output_type != RF_INT16_REAL)
	{
		fprintf(stderr, "CVBS output requires an unmodulated (baseband) mode.\n");
		return(RF_ERROR);
	}

	if(conf->invert_video)
	{
		fprintf(stderr, "CVBS output does not support inverted video.\n");
		return(RF_ERROR);
	}

	if(vid->pixel_rate != vid->sample_rate)
	{
		fprintf(stderr, "CVBS output requires the pixel rate to match the sample rate.\n");
		return(RF_ERROR);
	}

	/* The input must have an exact whole number of samples per line, or
	 * the frames written will drift against the 4 x fsc frame size */
	if(((int64_t) vid->sample_rate * conf->frame_rate.den) % (conf->frame_rate.num * conf->lines) != 0)
	{
		fprintf(stderr, "CVBS output requires a whole number of samples per line.\n");
		fprintf(stderr, "Try a sample rate of 20.25 MHz (-s 20250000).\n");
		return(RF_ERROR);
	}

	rf = calloc(1, sizeof(rf_cvbs_t));
	if(!rf)
	{
		perror("calloc");
		return(RF_OUT_OF_MEMORY);
	}

	/* Pick the video standard preset. The sample phase is the position of
	 * the first sample after 0H, in samples. With 0 degrees Sc/H this puts
	 * the PAL samples on the +/-U +/-V 45 degree axes, and the NTSC samples
	 * on the I and Q axes (33 degrees) */
	rf->signal_state = "STANDARD_STABLE_UNLOCKED";
	phase = (r64_t) { 1, 2 };

	if(conf->type == VID_RASTER_625 && conf->lines == 625 &&
	   r64_cmp(conf->frame_rate, (r64_t) { 25, 1 }) == 0)
	{
		if(conf->colour_mode == VID_PAL &&
		   r64_cmp(conf->colour_carrier, (r64_t) { 17734475, 4 }) == 0)
		{
			rf->preset = &_preset_pal;
			rf->signal_state = "STANDARD_STABLE_LOCKED";
		}
		else if(conf->colour_mode == VID_SECAM)
		{
			rf->preset = &_preset_secam;
		}
		else if(conf->colour_mode == VID_MONOCHROME)
		{
			rf->preset = &_preset_pal;
		}

		fsc4 = (r64_t) { 17734475, 1 };
	}
	else if(conf->type == VID_RASTER_525 && conf->lines == 525 &&
	   r64_cmp(conf->frame_rate, (r64_t) { 30000, 1001 }) == 0)
	{
		if(conf->colour_mode == VID_NTSC &&
		   r64_cmp(conf->colour_carrier, (r64_t) { 39375000, 11 }) == 0)
		{
			rf->preset = &_preset_ntsc;
			rf->signal_state = "STANDARD_STABLE_LOCKED";
			phase = (r64_t) { 11, 30 };
		}
		else if(conf->colour_mode == VID_PAL &&
		   r64_cmp(conf->colour_carrier, (r64_t) { 511312500, 143 }) == 0)
		{
			rf->preset = &_preset_pal_m;
		}
		else if(conf->colour_mode == VID_MONOCHROME)
		{
			rf->preset = &_preset_ntsc;
		}

		fsc4 = rf->preset == &_preset_pal_m ? (r64_t) { 511312500 * 4, 143 } : (r64_t) { 39375000 * 4, 11 };
	}

	if(rf->preset == NULL)
	{
		fprintf(stderr, "This mode cannot be stored as a CVBS file. Supported are 625-line PAL,\n");
		fprintf(stderr, "SECAM and monochrome, 525-line NTSC, PAL-M and monochrome baseband modes.\n");
		_free(rf);
		return(RF_ERROR);
	}

	rf->encoding = encoding;
	rf->yc = conf->s_video ? 1 : 0;
	rf->nch = rf->yc ? 2 : 1;
	rf->in_rate = (r64_t) { vid->sample_rate, 1 };
	rf->frame_rate = conf->frame_rate;
	rf->notes = strdup(notes ? notes : "");

	/* 10-bit units per int16 unit, using the white and blanking levels */
	rf->scale = (double) (rf->preset->white - rf->preset->blanking) / (vid->white_level - vid->blanking_level);
	rf->black_level = lround(rf->preset->blanking + (vid->black_level - vid->blanking_level) * rf->scale);

	/* Resampler setup. Output sample n is at input sample
	 * (n + phase) * in_rate / fsc4 = (n * phase.den + phase.num) * ratio / phase.den */
	ratio = r64_div(rf->in_rate, fsc4);
	rf->q = ratio.den * phase.den;
	rf->step_i = (ratio.num * phase.den) / rf->q;
	rf->step_f = (ratio.num * phase.den) % rf->q;
	rf->ip = (ratio.num * phase.num) / rf->q;
	rf->fr = (ratio.num * phase.num) % rf->q;

	cutoff = 0.45 * (fsc4.num < rf->in_rate.num * fsc4.den ? (double) fsc4.num / fsc4.den : rf->in_rate.num) / rf->in_rate.num;

	/* Strip a known extension from the filename to get the basename */
	rf->basename = strdup(filename);
	if(!rf->basename)
	{
		_free(rf);
		return(RF_OUT_OF_MEMORY);
	}

	ext = strrchr(rf->basename, '.');
	if(ext && (strcmp(ext, ".cvbs") == 0 || strcmp(ext, ".cvbsy") == 0 ||
	   strcmp(ext, ".cvbsc") == 0 || strcmp(ext, ".meta") == 0))
	{
		rf->basename[ext - rf->basename] = '\0';
	}

	r = _init_taps(rf, cutoff);

	/* The history buffer starts ntaps samples before the first input sample */
	rf->in_base = -rf->ntaps;

	if(r == RF_OK && rf->yc)
	{
		r = _open_channel(rf, &rf->ch[0], ".cvbsy", vid->blanking_level, rf->preset->blanking);
		if(r == RF_OK) r = _open_channel(rf, &rf->ch[1], ".cvbsc", 0, 512);
	}
	else if(r == RF_OK)
	{
		r = _open_channel(rf, &rf->ch[0], ".cvbs", vid->blanking_level, rf->preset->blanking);
	}

	if(r != RF_OK)
	{
		if(r == RF_OUT_OF_MEMORY) perror("malloc");
		_free(rf);
		return(r);
	}

#ifndef HAVE_SQLITE3
	fprintf(stderr, "CVBS: Warning: hacktv was built without SQLite, no .meta file will be written\n");
#endif

	/* Register the callback functions */
	s->ctx = rf;
	s->write = _rf_cvbs_write;
	s->close = _rf_cvbs_close;

	return(RF_OK);
}

