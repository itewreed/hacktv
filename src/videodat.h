#ifndef _VIDEODAT_H
#define _VIDEODAT_H

#include <stdio.h>
#include <stdint.h>
#include <time.h>
#include "video.h"
#include "vbidata.h"
#include "vdpacket.h"

/* Each VBI line carries 10 bytes as NRZ at 2 Mbit/s */
#define VD_LINE_BYTES (10)
#define VD_LINE_BITS (VD_LINE_BYTES * 10)
#define VD_BIT_RATE (2.0e6)

/* Bit n of a line mask is line 7 + n (first field) or 320 + n
 * (second field). The default is lines 11-13 and 324-326, where
 * Pro7 sent it. */
#define VD_DEFAULT_MASK (0x0070)

typedef struct {
	char name[13];
	uint8_t *data;
	uint32_t size;
	time_t mtime;
} vd_file_t;

typedef struct {
	vid_t *vid;
	vbidata_lut_t *lut;
	uint16_t mask[2];
	
	/* Raw byte stream input (raw:<path>) */
	FILE *raw;
	int raw_eof;
	
	/* Generated byte stream (demo or files) */
	uint8_t *buf;
	size_t buf_len;
	size_t buf_pos;
	size_t buf_size;
	
	vd_tx_t tx;
	vd_stream_t stream;
	vd_stream_t clock;
	
	uint64_t bytes_out;
	double rate;
	double next_clock;
	time_t t0;
	
	const char *info;
	vd_file_t *files;
	int nfiles;
	int next_file;
	
} videodat_t;

extern int videodat_init(videodat_t *s, vid_t *vid, const char *source, const char *lines, const char *info);
extern void videodat_free(videodat_t *s);
extern int videodat_render(vid_t *s, void *arg, int nlines, vid_line_t **lines);

#endif

